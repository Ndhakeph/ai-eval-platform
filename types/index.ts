/**
 * Core TypeScript interfaces for the AI Evaluation Platform.
 *
 * The platform is stateless: there is no database. These types describe the
 * shapes that flow between the baked sample data, the live judge endpoints,
 * and the UI. Live results and baked results share the same shapes so every
 * surface can render either interchangeably.
 */

/** The three rubric criteria the judge scores against. */
export type Criterion = 'accuracy' | 'clarity' | 'completeness';

export const CRITERIA: Criterion[] = ['accuracy', 'clarity', 'completeness'];

/** Numeric scores for the three rubric criteria (each 0-10). */
export interface RubricScores {
  accuracy: number;
  clarity: number;
  completeness: number;
}

/** A single criterion's score paired with the judge's written reasoning. */
export interface CriterionDetail {
  /** 0-10, may be a decimal. */
  score: number;
  /** The judge's justification for this score. */
  reasoning: string;
}

/**
 * A fully scored single output. Returned by the live `/api/evaluate` endpoint
 * and used as the shape of every baked single-scoring example.
 */
export interface ScoredEvaluation {
  id: string;
  /** Subject area, e.g. "Coding", "Medical", used for grouping on the dashboard. */
  domain: string;
  prompt: string;
  /** The model output being judged (never regenerated by this platform). */
  output: string;
  /** Optional gold/reference answer the output is judged against. */
  reference?: string;
  accuracy: CriterionDetail;
  clarity: CriterionDetail;
  completeness: CriterionDetail;
  /** Real decimal average of the three criteria — never rounded to an int. */
  total_score: number;
  model_used: string;
}

/** A judge's verdict for one criterion in a pairwise comparison. */
export interface CriterionVerdict {
  winner: 'A' | 'B' | 'tie';
  reasoning: string;
}

/**
 * The result of judging a pair in ONE presentation order. `firstShown` records
 * which output the judge saw first — the whole point of running both orders is
 * to detect when this changes the verdict (position bias).
 */
export interface OrderingResult {
  firstShown: 'A' | 'B';
  accuracy: CriterionVerdict;
  clarity: CriterionVerdict;
  completeness: CriterionVerdict;
  overall: CriterionVerdict;
}

/**
 * A full A/B comparison: the prompt, both outputs, the judge's verdict in both
 * presentation orders, and whether swapping the order flipped the overall
 * winner (position bias).
 */
export interface ABComparison {
  id: string;
  domain: string;
  prompt: string;
  outputA: string;
  outputB: string;
  /** Verdict when A was presented first. */
  orderingAB: OrderingResult;
  /** Verdict when B was presented first. */
  orderingBA: OrderingResult;
  /** True when the two orderings disagree on the overall winner. */
  positionBias: boolean;
  /** The agreed winner across both orders, or null when the judge is inconsistent. */
  consistentWinner: 'A' | 'B' | 'tie' | null;
  model_used: string;
}

/** A row parsed from an uploaded CSV. */
export interface TestCaseCSVRow {
  prompt: string;
  output: string;
  reference?: string;
}

/** Aggregate statistics rendered on the dashboard. */
export interface DashboardStats {
  totalEvaluations: number;
  averageTotal: number;
  averageAccuracy: number;
  averageClarity: number;
  averageCompleteness: number;
  domainCount: number;
  comparisonCount: number;
  positionBiasRate: number;
}

/** Discriminated error codes returned by the live endpoints so the UI can react calmly. */
export type ApiErrorCode = 'no_api_key' | 'rate_limited' | 'bad_request' | 'judge_failed';
